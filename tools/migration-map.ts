/**
 * Where every collection's content came from.
 *
 * One entry per collection: which `src/data` module held it, which `const`
 * inside that module, and how that const was shaped. `infer-content-model`
 * reads this to turn `seed/legacy/*.json` into records, and to write the
 * collection definitions the admin renders forms from.
 *
 * Two rules decided what became a collection and what stayed in code:
 *
 *   - Content moves. Anything a person at the university would want to
 *     change — a name, a date, a photograph, a paragraph, a price.
 *   - Identity stays. The key lists that drive routes, colours and message
 *     lookups (`SCHOOL_KEYS`, `MEDIA_DESKS`, `CONFERENCE_SLUGS`,
 *     `FACULTY_RANKS`, …) are union types that 144 components depend on.
 *     An editor removing a school key would not edit the site, it would
 *     break the build. Those are still TypeScript.
 *
 * `sources/navigator.json` and `sources/clubs.json` are deliberately absent:
 * nothing in `src/` imports them. They are leftovers from the prototype and
 * carry no live content.
 */

/** How the extracted value is laid out, and so how it becomes records. */
export type SourceShape =
  /** a plain array of records */
  | { kind: "array" }
  /**
   * An object keyed by a domain key, each value an array of records —
   * `{ business: [...], law: [...] }`. The key is written onto every record
   * as `keyField` so one flat collection can serve all five schools.
   */
  | { kind: "byKey"; keyField: string; wrapField?: string }
  /**
   * An object keyed by the record's own identity —
   * `{ "american-studies": {...} }`. The key becomes `keyField`.
   *
   * `wrapField` is for values that are not objects: a story body is an
   * array of blocks, so it is stored as `{ storyId, blocks: [...] }`
   * rather than spread over the record.
   */
  | { kind: "objectMap"; keyField: string; wrapField?: string }
  /**
   * Two levels of the above: `{ stories: { "4101": … }, columns: { … } }`.
   * Both keys are written onto the record.
   */
  | { kind: "nestedMap"; outerField: string; keyField: string }
  /**
   * An object keyed by locale, each value an array —
   * `{ ka: [...], en: [...] }`. The two languages hold *different numbers
   * of items* (the Georgian documentation list is 45 files where the
   * English one is 77), so these cannot be zipped into bilingual rows.
   * Each language's items become their own records, tagged with `locale`.
   */
  | { kind: "byLocale" }
  /** a single object: one record, no list */
  | { kind: "object" }
  /** several named constants gathered into one settings record */
  | { kind: "constants"; names: string[] };

export interface MigrationEntry {
  /** the collection name: its API path and its `records.collection` value */
  collection: string;
  label: string;
  group: string;
  kind: "list" | "singleton";
  description?: string;
  /** `src/data/<module>.ts`, or `sources/<file>.json` when `fromSource` */
  module: string;
  /** the `const` inside it; ignored for `constants` shapes */
  constName?: string;
  /** a path *inside* the const, e.g. `stories` for `BODIES.stories` */
  constPath?: string;
  /** read from `seed/legacy/sources/<file>.json` instead of a module */
  fromSource?: string;
  /** a path into the source JSON, e.g. `clubs` for `{ clubs: [...] }` */
  sourcePath?: string;
  shape: SourceShape;
  titleField: string;
  keyField?: string;
  sortable?: boolean;
  sortField?: string;
  sortDirection?: "asc" | "desc";
  tags: string[];
  routes?: string[];
}

